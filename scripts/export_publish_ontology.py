#!/usr/bin/env python3
"""Write the publish tool's copy of the ontology.

    export_publish_ontology.py            write tools/publish/lib/ontology.json
    export_publish_ontology.py --print    print it instead

The site colours a relationship by its tone's family and words a group
by its predicate; `relationships words` and `relationships check` read the
vocabulary, tones, strength, verbs and place rules. It carries those and
nothing else (no mobRPG mapping). The copy is generated;
tests/test_publish_ontology.py fails when it is stale.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "skills" / "shared" / "gm-apprentice-ontology.json"
COPY = REPO / "tools" / "publish" / "lib" / "ontology.json"
KEYS = ("type", "inverse", "category", "symmetric", "genre")
# Top-level keys copied whole: `relationships words` prints the tones and strength, and
# `relationships check` (Task 7) reads the verbs, same-fact pairs, place fields and the
# entity types an edge may not point at.
TOP_KEYS = ("tones", "tone_near", "strength_scale", "storage_rule", "verbs", "same_fact",
            "place_fields", "not_edge_target_types")
FAMILIES = ("positive", "negative", "neutral")


def export(full: dict | None = None) -> str:
    if full is None:
        full = json.loads(SOURCE.read_text(encoding="utf-8"))
    # The site shows a tone as warm (positive), hostile (negative) or neutral and has no
    # colour for any other family, so one more would be published as nothing.
    if set(full["tones"]) != set(FAMILIES):
        raise ValueError(
            f"tones holds the families {sorted(full['tones'])}; the site shows only "
            f"{', '.join(FAMILIES)}. Add a colour for the new family to the site first, "
            "or fold its words into one of those")
    out = {
        "$comment": "Generated by scripts/export_publish_ontology.py from "
                    "skills/shared/gm-apprentice-ontology.json. Do not edit.",
        **{k: full[k] for k in TOP_KEYS},
        "predicates": [{k: p[k] for k in KEYS} for p in full["predicates"]],
    }
    return json.dumps(out, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    try:
        text = export()
    except ValueError as err:
        print(f"error: {SOURCE.name}: {err}", file=sys.stderr)
        return 1
    if "--print" in argv:
        # Bytes, so Windows does not turn the newlines into CRLF.
        sys.stdout.buffer.write(text.encode("utf-8"))
        sys.stdout.buffer.flush()
    else:
        COPY.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {COPY.relative_to(REPO).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
